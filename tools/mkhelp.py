#!/usr/bin/env python3
"""AETHER - by Synth Centric
Builds src/interface/help_data.c (contextual help panel) from assets/help.txt."""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
entries, seen = [], {}
for ln, line in enumerate(open(os.path.join(ROOT, "assets/help.txt")), 1):
    line = line.rstrip("\n")
    if not line or line.startswith("#"):
        continue
    parts = line.split("|")
    key, l1 = parts[0], parts[1] if len(parts) > 1 else ""
    l2 = parts[2] if len(parts) > 2 else ""
    for l in (l1, l2):
        if len(l) > 20:
            sys.exit("help.txt:%d line too long (%d): %s" % (ln, len(l), l))
    if key in seen:
        sys.exit("help.txt:%d duplicate key %s (first at %d)" % (ln, key, seen[key]))
    seen[key] = ln
    entries.append((key, l1, l2))
def c(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["/* AETHER - by Synth Centric",
       " * GENERATED by tools/mkhelp.py from assets/help.txt - do not edit. */",
       "#pragma bank 255",
       "#include <string.h>",
       '#include "gfx.h"',
       "#define NHELP %d" % len(entries),
       "static const char * const help_key[NHELP] = {"]
out += ["    %s," % c(k) for k, _, _ in entries] + ["};", "static const char * const help_txt[NHELP][2] = {"]
out += ["    { %s, %s }," % (c(a), c(b)) for _, a, b in entries] + ["};", """
/* key: RAM copy of a label; out: 2 x 21 chars */
void help_lookup(const char *key, char *out) BANKED
{
    uint8_t i;
    out[0] = 0; out[21] = 0;
    for (i = 0; i < NHELP; i++) {
        if (!strcmp(help_key[i], key)) {
            strcpy(out, help_txt[i][0]);
            strcpy(out + 21, help_txt[i][1]);
            return;
        }
    }
}
"""]
path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src/interface/help_data.c")
open(path, "w").write("\n".join(out))
print("wrote", path, len(entries), "entries")
