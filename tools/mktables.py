#!/usr/bin/env python3
"""AETHER - by Synth Centric
Generates src/audio/tables.c : pitch -> frequency register tables for the
Game Boy pulse/wave channels and a perceptually ordered noise (NR43) table.
"""
import math, os, sys

out = []
out.append("/* AETHER - by Synth Centric\n * GENERATED by tools/mktables.py - do not edit by hand. */")
out.append('#include "aether.h"\n')
# pulse: f = 131072 / (2048 - x)  -> MIDI 36..107
vals = []
for m in range(36, 108):
    f = 440.0 * 2 ** ((m - 69) / 12)
    x = int(round(2048 - 131072 / f))
    x = max(0, min(2047, x))
    vals.append(x)
out.append("/* pulse channel frequency register, MIDI note 36 (C2) .. 107 (B7).\n * The wave channel plays one octave lower for the same value. */")
out.append("const uint16_t freq_table[72] = {")
for i in range(0, 72, 12):
    out.append("    " + ", ".join(str(v) for v in vals[i:i+12]) + ",")
out.append("};\n")

# noise: freq = 524288 / r' / 2^(s+1), r' = 0.5 for r = 0
combos = []
for s in range(0, 14):
    for r in range(0, 8):
        rr = 0.5 if r == 0 else r
        f = 524288 / rr / (2 ** (s + 1))
        combos.append((f, s, r))
lo, hi = 16.0, 262144.0
sel = []
for i in range(24):
    t = lo * (hi / lo) ** (i / 23)
    best = min(combos, key=lambda c: abs(math.log(c[0] / t)))
    sel.append(best)
out.append("/* noise NR43 (without width bit), ordered from low rumble to bright hiss */")
out.append("const uint8_t noise_table[24] = {")
out.append("    " + ", ".join("0x%02X" % ((s << 4) | r) for f, s, r in sel) + ",")
out.append("};")
path = sys.argv[1] if len(sys.argv) > 1 else "src/audio/tables.c"
open(path, "w").write("\n".join(out) + "\n")
print("wrote", path)
